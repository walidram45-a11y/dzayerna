/* ---------------- Small pieces ---------------- */

function Chip({ icon, text }) {
  return (
    <View style={s.chip}>
      <Ionicons name={icon} size={13} color={C.green} />
      <Text style={s.chipText}>{text}</Text>
    </View>
  );
}

function ProcRow({ proc, onPress }) {
  return (
    <TouchableOpacity style={s.row} activeOpacity={0.7} onPress={onPress}>
      <Ionicons name="chevron-back" size={18} color={C.textMuted} />
      <View style={{ flex: 1 }}>
        <View style={{ flexDirection: "row-reverse", alignItems: "center", gap: 8, flexWrap: "wrap" }}>
          <Text style={s.rowTitle}>{proc.title}</Text>
          {proc.forExpats ? (
            <View style={s.badge}>
              <Text style={s.badgeText}>مغتربين</Text>
            </View>
          ) : null}
        </View>
        <Text style={s.rowSub}>{proc.sub}</Text>
      </View>
    </TouchableOpacity>
  );
}

/* ---------------- Home screen ---------------- */

function HomeScreen({ onOpenCategory, onOpenProc }) {
  const [query, setQuery] = useState("");

  const countByCategory = useMemo(() => {
    const m = {};
    PROCS.forEach((p) => {
      m[p.cat] = (m[p.cat] || 0) + 1;
    });
    return m;
  }, []);

  const results = useMemo(() => {
    if (!query.trim()) return null;
    const q = query.trim();
    return PROCS.filter((p) => p.title.includes(q) || p.sub.includes(q));
  }, [query]);

  return (
    <SafeAreaView style={{ flex: 1, backgroundColor: C.bg }}>
      <ScrollView contentContainerStyle={{ paddingBottom: 30 }}>
        <View style={s.header}>
          <View style={{ flex: 1 }}>
            <Text style={s.greeting}>مرحبًا بيك 👋</Text>
            <View style={{ flexDirection: "row-reverse", alignItems: "baseline", gap: 7 }}>
              <Text style={s.title}>دزايرنا</Text>
              <Text style={s.subtitle}>Dzayerna</Text>
            </View>
          </View>
          <Text style={{ fontSize: 34 }}>🇩🇿</Text>
        </View>

        <Text style={s.tagline}>كل الإجراءات الإدارية في الجزائر، لأهل الوطن وأبناء الجالية، فمكان واحد.</Text>

        <View style={s.searchBar}>
          <Ionicons name="search" size={18} color={C.green} />
          <TextInput
            value={query}
            onChangeText={setQuery}
            placeholder="ابحث عن إجراء... جواز السفر، عقد الزواج..."
            placeholderTextColor={C.textMuted}
            style={s.searchInput}
          />
        </View>

        {results ? (
          <View style={{ paddingHorizontal: 18, marginTop: 16, gap: 10 }}>
            <Text style={{ color: C.textMuted, fontSize: 12.5 }}>{results.length} نتيجة</Text>
            {results.map((p) => (
              <ProcRow key={p.id} proc={p} onPress={() => onOpenProc(p.id)} />
            ))}
          </View>
        ) : (
          <View style={s.grid}>
            {CATEGORIES.map((cat) => (
              <TouchableOpacity key={cat.id} style={s.card} activeOpacity={0.75} onPress={() => onOpenCategory(cat.id)}>
                <Text style={s.cardLabel}>{cat.label}</Text>
                <View style={s.cardBottomRow}>
                  <View style={s.countBadge}>
                    <Text style={s.countText}>{countByCategory[cat.id] || 0}</Text>
                  </View>
                  <Ionicons name={cat.icon} size={32} color={C.green} />
                </View>
              </TouchableOpacity>
            ))}
          </View>
        )}
      </ScrollView>
    </SafeAreaView>
  );
}

/* ---------------- Category screen ---------------- */

function CategoryScreen({ catId, onBack, onOpenProc }) {
  const cat = CATEGORIES.find((c) => c.id === catId);
  const items = PROCS.filter((p) => p.cat === catId);
  return (
    <SafeAreaView style={{ flex: 1, backgroundColor: C.bg }}>
      <View style={s.topBar}>
        <TouchableOpacity onPress={onBack} style={s.backBtn}>
          <Ionicons name="chevron-forward" size={20} color={C.text} />
        </TouchableOpacity>
        <Text style={s.topBarTitle}>{cat ? cat.label : ""}</Text>
        <View style={{ width: 36 }} />
      </View>
      <FlatList
        contentContainerStyle={{ padding: 16, gap: 10 }}
        data={items}
        keyExtractor={(p) => p.id}
        renderItem={({ item }) => <ProcRow proc={item} onPress={() => onOpenProc(item.id)} />}
      />
    </SafeAreaView>
  );
}

/* ---------------- Detail screen ---------------- */

function DetailScreen({ procId, onBack }) {
  const proc = PROCS.find((p) => p.id === procId);
  const [checked, setChecked] = useState({});
  if (!proc) return null;
  const toggle = (i) => setChecked((c) => ({ ...c, [i]: !c[i] }));

  return (
    <SafeAreaView style={{ flex: 1, backgroundColor: C.bg }}>
      <View style={s.topBar}>
        <TouchableOpacity onPress={onBack} style={s.backBtn}>
          <Ionicons name="chevron-forward" size={20} color={C.text} />
        </TouchableOpacity>
        <Text style={s.topBarTitle} numberOfLines={1}>{proc.title}</Text>
        <View style={{ width: 36 }} />
      </View>
      <ScrollView contentContainerStyle={{ padding: 20 }}>
        {proc.forExpats ? (
          <View style={[s.badge, { alignSelf: "flex-start", marginBottom: 8 }]}>
            <Text style={s.badgeText}>الجالية بالخارج</Text>
          </View>
        ) : null}
        <Text style={s.detailSub}>{proc.sub}</Text>

        <View style={s.chipRow}>
          <Chip icon="location-outline" text={proc.where} />
          <Chip icon="time-outline" text={proc.duration} />
          {proc.fees ? <Chip icon="cash-outline" text={proc.fees} /> : null}
        </View>

        <Text style={s.sectionTitle}>الوثائق المطلوبة</Text>
        <View style={{ gap: 8, marginBottom: 20 }}>
          {proc.docs.map((d, i) => (
            <TouchableOpacity key={i} style={s.docRow} onPress={() => toggle(i)} activeOpacity={0.6}>
              <View style={[s.checkbox, checked[i] && { backgroundColor: C.green }]} />
              <Text style={[s.docText, checked[i] && s.docTextChecked]}>{d}</Text>
            </TouchableOpacity>
          ))}
        </View>

        <Text style={s.sectionTitle}>خطوات الإجراء</Text>
        <View style={{ gap: 14, marginBottom: 20 }}>
          {proc.steps.map((step, i) => (
            <View key={i} style={s.stepRow}>
              <View style={s.stepNum}>
                <Text style={s.stepNumText}>{i + 1}</Text>
              </View>
              <Text style={s.stepText}>{step}</Text>
            </View>
          ))}
        </View>

        {proc.note ? (
          <View style={s.noteBox}>
            <Ionicons name="alert-circle-outline" size={18} color={C.red} />
            <Text style={s.noteText}>{proc.note}</Text>
          </View>
        ) : null}
      </ScrollView>
    </SafeAreaView>
  );
}

/* ---------------- App root (simple stack via useState) ---------------- */

export default function App() {
  const [screen, setScreen] = useState({ name: "home" });

  if (screen.name === "category") {
    return (
      <CategoryScreen
        catId={screen.catId}
        onBack={() => setScreen({ name: "home" })}
        onOpenProc={(procId) => setScreen({ name: "detail", procId, back: screen })}
      />
    );
  }
  if (screen.name === "detail") {
    return <DetailScreen procId={screen.procId} onBack={() => setScreen(screen.back || { name: "home" })} />;
  }
  return (
    <HomeScreen
      onOpenCategory={(catId) => setScreen({ name: "category", catId })}
      onOpenProc={(procId) => setScreen({ name: "detail", procId, back: { name: "home" } })}
    />
  );
}

